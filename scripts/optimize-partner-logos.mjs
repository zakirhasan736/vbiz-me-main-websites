import fs from 'node:fs/promises';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const SRC_DIR = path.join(ROOT, 'public', 'partner-logo');
const OUT_DIR = path.join(ROOT, 'public', 'partner-logo-optimized');
const MANIFEST_PATH = path.join(ROOT, 'src', 'lib', 'partner-logos.manifest.ts');

/** Match marquee display cell — avoids overserving pixels */
const MAX_WIDTH = 140;
const MAX_HEIGHT = 56;
const DEFAULT_QUALITY = 48;
/** Logos flagged by Lighthouse — compress a bit harder */
const HEAVY_QUALITY = 38;
const HEAVY_LOGO_IDS = new Set(['5', '10']);

const IMAGE_EXT = new Set(['.png', '.jpg', '.jpeg', '.webp']);
const VIDEO_EXT = new Set(['.mp4', '.webm', '.mov']);

let sharp;
try {
  sharp = (await import('sharp')).default;
} catch {
  console.warn(
    '⚠ sharp is not installed — skipping partner logo optimization.\n' +
      '  Run `npm install` (includes devDependencies) or commit public/partner-logo-optimized/*.webp.',
  );
  process.exit(0);
}

function slugFromFilename(filename) {
  const numbered = filename.match(/^partner-logo-(\d+)\./i);
  if (numbered) return `partner-logo-${numbered[1]}`;

  return path
    .parse(filename)
    .name.toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function altFromSlug(slug) {
  const numbered = slug.match(/^partner-logo-(\d+)$/);
  if (numbered) return `Partner company logo ${numbered[1]}`;

  const words = slug
    .split('-')
    .filter(Boolean)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1));

  if (words[words.length - 1]?.toLowerCase() === 'logo') {
    return words.join(' ');
  }

  return `${words.join(' ')} logo`;
}

function sortManifest(a, b) {
  const na = a.slug.match(/^partner-logo-(\d+)$/);
  const nb = b.slug.match(/^partner-logo-(\d+)$/);
  if (na && nb) return Number(na[1]) - Number(nb[1]);
  if (na) return -1;
  if (nb) return 1;
  return a.slug.localeCompare(b.slug);
}

async function optimizeImage(filename) {
  const ext = path.extname(filename).toLowerCase();
  if (!IMAGE_EXT.has(ext)) return null;

  const slug = slugFromFilename(filename);
  const input = path.join(SRC_DIR, filename);
  const output = path.join(OUT_DIR, `${slug}.webp`);
  const numbered = slug.match(/^partner-logo-(\d+)$/);
  const quality =
    numbered && HEAVY_LOGO_IDS.has(numbered[1]) ? HEAVY_QUALITY : DEFAULT_QUALITY;

  await sharp(input)
    .resize(MAX_WIDTH, MAX_HEIGHT, {
      fit: 'inside',
      withoutEnlargement: true,
    })
    .webp({ quality, effort: 6, smartSubsample: true, alphaQuality: quality })
    .toFile(output);

  const { size } = await fs.stat(output);
  console.log(`✓ ${slug}.webp (${size} bytes, q${quality})`);

  return {
    slug,
    src: `/partner-logo-optimized/${slug}.webp`,
    alt: altFromSlug(slug),
    kind: 'image',
  };
}

async function copyVideo(filename) {
  const ext = path.extname(filename).toLowerCase();
  if (!VIDEO_EXT.has(ext)) return null;

  const slug = slugFromFilename(filename);
  const input = path.join(SRC_DIR, filename);
  const output = path.join(OUT_DIR, `${slug}${ext}`);

  await fs.copyFile(input, output);
  const { size } = await fs.stat(output);
  console.log(`✓ ${slug}${ext} (${size} bytes, video copy)`);

  return {
    slug,
    src: `/partner-logo-optimized/${slug}${ext}`,
    alt: altFromSlug(slug),
    kind: 'video',
  };
}

async function writeManifest(entries) {
  const sorted = [...entries].sort(sortManifest);
  const lines = sorted.map((entry) => {
    const kind = entry.kind === 'video' ? ", kind: 'video'" : '';
    return `  { src: '${entry.src}', alt: '${entry.alt.replace(/'/g, "\\'")}'${kind} },`;
  });

  const content = `/** Auto-generated by scripts/optimize-partner-logos.mjs — do not edit manually. */
export const PARTNER_LOGOS_MANIFEST = [
${lines.join('\n')}
] as const;

export type PartnerLogoManifestEntry = (typeof PARTNER_LOGOS_MANIFEST)[number];
`;

  await fs.writeFile(MANIFEST_PATH, content, 'utf8');
  console.log(`✓ manifest (${sorted.length} logos) → src/lib/partner-logos.manifest.ts`);
}

await fs.mkdir(OUT_DIR, { recursive: true });
await fs.mkdir(SRC_DIR, { recursive: true });

const entries = await fs.readdir(SRC_DIR);
const manifest = [];

for (const entry of entries.sort((a, b) => a.localeCompare(b, undefined, { sensitivity: 'base' }))) {
  const ext = path.extname(entry).toLowerCase();
  if (IMAGE_EXT.has(ext)) {
    const item = await optimizeImage(entry);
    if (item) manifest.push(item);
  } else if (VIDEO_EXT.has(ext)) {
    const item = await copyVideo(entry);
    if (item) manifest.push(item);
  }
}

if (manifest.length === 0) {
  console.warn('⚠ No partner logos found in public/partner-logo');
  process.exit(0);
}

await writeManifest(manifest);
